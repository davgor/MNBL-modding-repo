"""MMR-286: the module's localization strings, ModuleData/Languages/std_mnbl_procedural_world.xml.

Every player-facing text of MNBL.ProceduralWorld is a "{=id}default text" string literal (TaleWorlds TextObject form; the setup and
preview screens, generation errors, load refusals and warnings, the loader's messages, the ruins page, the speed tooltip). This tool
collects every such literal whose id starts with mnbl_ from src/MNBL.ProceduralWorld/**/*.cs and writes them, sorted by id, in the
installed game's string file form (as Modules/SandBox/ModuleData/Languages/std_SandBox.xml: the English base a translation copies;
the game shows the inline default text in English, so no language_data.xml is needed). An id used with two different texts is refused.
World-specific record names ({=mnbl_<world prefix>_...}) are compiled per world and are not module strings.

Usage: python tools/make_module_strings.py [--check]   (--check: exit 1 when the file differs from the sources)
"""
import os
import re
import sys
from xml.sax.saxutils import quoteattr

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = os.path.join(REPO, 'src', 'MNBL.ProceduralWorld')
OUT = os.path.join(REPO, 'Modules', 'MNBL.ProceduralWorld', 'ModuleData', 'Languages', 'std_mnbl_procedural_world.xml')
LITERAL = re.compile(r'@"((?:[^"]|"")*)"|"((?:[^"\\\n]|\\.)*)"')
ID = re.compile(r'^\{=(mnbl_[a-z0-9_]+)\}')
WORLD_ID = re.compile(r'^mnbl_[0-9a-f]{8}_')
ESCAPES = {'n': '\n', 't': '\t', 'r': '\r', '"': '"', "'": "'", '\\': '\\', '0': '\0'}


def unescape(text):
    out, i = [], 0
    while i < len(text):
        c = text[i]
        if c == '\\' and i + 1 < len(text):
            n = text[i + 1]
            if n == 'u':
                out.append(chr(int(text[i + 2:i + 6], 16)))
                i += 6
                continue
            out.append(ESCAPES.get(n, n))
            i += 2
            continue
        out.append(c)
        i += 1
    return ''.join(out)


def strip_comments(code):
    # Line and block comments go, string literals stay (a "//" inside a literal is not a comment).
    out, i, n = [], 0, len(code)
    while i < n:
        if code.startswith('//', i):
            j = code.find('\n', i)
            i = n if j < 0 else j
        elif code.startswith('/*', i):
            j = code.find('*/', i + 2)
            i = n if j < 0 else j + 2
        elif code.startswith('@"', i):
            j = i + 2
            while j < n and not (code[j] == '"' and not code.startswith('""', j)):
                j += 2 if code.startswith('""', j) else 1
            out.append(code[i:j + 1])
            i = j + 1
        elif code[i] == '"':
            j = i + 1
            while j < n and code[j] != '"' and code[j] != '\n':
                j += 2 if code[j] == '\\' else 1
            out.append(code[i:j + 1])
            i = j + 1
        elif code[i] == "'":
            j = i + 1
            while j < n and code[j] != "'" and code[j] != '\n':
                j += 2 if code[j] == '\\' else 1
            out.append(code[i:j + 1])
            i = j + 1
        else:
            out.append(code[i])
            i += 1
    return ''.join(out)


def collect():
    strings, where = {}, {}
    problems = []
    for folder, dirs, files in os.walk(SOURCES):
        dirs[:] = sorted(d for d in dirs if d not in ('obj', 'bin'))
        for name in sorted(files):
            if not name.endswith('.cs'):
                continue
            path = os.path.join(folder, name)
            with open(path, encoding='utf-8-sig') as f:
                code = strip_comments(f.read())
            rel = os.path.relpath(path, REPO).replace(os.sep, '/')
            for m in LITERAL.finditer(code):
                text = m.group(1).replace('""', '"') if m.group(1) is not None else unescape(m.group(2))
                idm = ID.match(text)
                if not idm or WORLD_ID.match(idm.group(1)):
                    continue
                sid, body = idm.group(1), text[idm.end():]
                if sid in strings and strings[sid] != body:
                    problems.append('%s: id %s has two texts (%s; %s)' % (rel, sid, where[sid], rel))
                    continue
                strings[sid], where[sid] = body, where.get(sid, rel)
    return strings, problems


def document(strings):
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             '<!-- Generated by tools/make_module_strings.py from the module\'s "{=id}text" literals (MMR-286). Do not edit by hand. -->',
             '<base xmlns:xsi="http://www.w3.org/2001/XMLSchema-instance" xmlns:xsd="http://www.w3.org/2001/XMLSchema" type="string">',
             '  <tags>', '    <tag language="English" />', '  </tags>', '  <strings>']
    for sid in sorted(strings):
        lines.append('    <string id=%s text=%s />' % (quoteattr(sid), quoteattr(strings[sid], {'\n': '&#10;', '\r': '&#13;', '\t': '&#9;'})))
    lines += ['  </strings>', '</base>', '']
    return '\n'.join(lines)


def main(argv):
    strings, problems = collect()
    if problems:
        print('\n'.join(problems))
        return 1
    text = document(strings)
    if '--check' in argv:
        current = open(OUT, encoding='utf-8').read() if os.path.exists(OUT) else ''
        if current != text:
            print('differs: %s (run python tools/make_module_strings.py)' % os.path.relpath(OUT, REPO))
            return 1
        print('current: %d module strings' % len(strings))
        return 0
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d module strings' % (os.path.relpath(OUT, REPO), len(strings)))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
