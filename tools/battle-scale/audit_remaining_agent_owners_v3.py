def binding_matches(callback_id, block, parameters):
    return (callback_id == 625 and len(block) == 7
            and block[1] == 'IL_4c96: ldtoken ManagedCallbacks.ScriptingInterfaceOfIMBPeer/SendExistingObjectsDelegate'
            and block[5] == 'IL_4caa: stsfld ManagedCallbacks.ScriptingInterfaceOfIMBPeer/SendExistingObjectsDelegate ManagedCallbacks.ScriptingInterfaceOfIMBPeer::call_SendExistingObjectsDelegate'
            and parameters == [{'name': 'index', 'type': 'System.Int32'}, {'name': 'missionPointer', 'type': 'System.UIntPtr'}])


def build():
    prior_path = ROOT / 'evidence/engine-extension/native-remaining-agent-owner-proofs-v2.json'
    assert digest(prior_path) == 'ea28a0415a95a3462d158d1493532aa3a9b4b884b0e32f2154896a6b1bb864aa'
    prior = json.loads(prior_path.read_text())
    deps = {d['path']: d['sha256'] for d in prior['dependencies']}
    deps[str(prior_path)] = digest(prior_path)
    deps[str(Path(__file__))] = digest(__file__)
    native_reg_path = ROOT / 'evidence/engine-extension/native-registration.json'
    assert digest(native_reg_path) == '737c039c61f82d6188119760907accd8c279d7255af3d01470f8d7e5efd1706e'
