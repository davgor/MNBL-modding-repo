    for path, sha in deps.items(): assert digest(path) == sha, path
    metadata = json.loads(subprocess.run([shutil.which('pwsh') or 'powershell', '-NoProfile', '-NonInteractive', '-Command', METADATA_SCRIPT],
        capture_output=True, text=True, check=True).stdout)
    assert [a['sha256'] for a in metadata['artifacts']] == [
        'b392461201996aec3dc5b7b3b0a4f57918f712681d3d6c32bc398df633662174',
        '19387f31557ff840d14f378f6bbdf1d58fcff406ab9ff2294dfbb3e49a50b87e']
    for a in metadata['artifacts'] + [metadata['cecil']]:
        assert digest(a['path']) == a['sha256']
        deps[a['path']] = a['sha256']
    methods = {m['name'].split('::')[0].split(' ', 1)[1]: m for m in metadata['methods']}
    delegate = methods['ManagedCallbacks.ScriptingInterfaceOfIMBPeer/SendExistingObjectsDelegate']
    wrapper = methods['ManagedCallbacks.ScriptingInterfaceOfIMBPeer']
    peer = methods['TaleWorlds.MountAndBlade.PeerExtensions']
    getter = methods['TaleWorlds.MountAndBlade.Mission']
    assert delegate['returnType'] == 'System.Void'
    assert binding_matches(metadata['registration']['callbackId'], metadata['registration']['block'], delegate['parameters'])
    assert metadata['registration']['prefix'] == ['IL_0000: ldarg.0', 'IL_0001: stloc.0', 'IL_0002: ldloc.0']
    assert {'name': 'System.Runtime.InteropServices.UnmanagedFunctionPointerAttribute', 'arguments': [3]} in metadata['delegateAttributes']
    assert wrapper['instructions'] == [
        'IL_0000: ldsfld ManagedCallbacks.ScriptingInterfaceOfIMBPeer/SendExistingObjectsDelegate ManagedCallbacks.ScriptingInterfaceOfIMBPeer::call_SendExistingObjectsDelegate',
        'IL_0005: ldarg.1', 'IL_0006: ldarg.2',
        'IL_0007: callvirt System.Void ManagedCallbacks.ScriptingInterfaceOfIMBPeer/SendExistingObjectsDelegate::Invoke(System.Int32,System.UIntPtr)', 'IL_000c: ret']
    assert peer['isStatic'] and peer['instructions'] == [
        'IL_0000: ldsfld TaleWorlds.MountAndBlade.IMBPeer TaleWorlds.MountAndBlade.MBAPI::IMBPeer',
        'IL_0005: ldarg.0', 'IL_0006: callvirt System.Int32 TaleWorlds.MountAndBlade.NetworkCommunicator::get_Index()',
        'IL_000b: ldarg.1', 'IL_000c: callvirt System.UIntPtr TaleWorlds.MountAndBlade.Mission::get_Pointer()',
        'IL_0011: callvirt System.Void TaleWorlds.MountAndBlade.IMBPeer::SendExistingObjects(System.Int32,System.UIntPtr)', 'IL_0016: ret']
    assert getter['instructions'] == ['IL_0000: ldarg.0',
        'IL_0001: ldfld System.UIntPtr TaleWorlds.MountAndBlade.Mission::<Pointer>k__BackingField', 'IL_0006: ret']
    ns = read_namespace()
    pe, base, rec = ns['pe'], ns['base'], ns['flow'].basic
    assert hashlib.sha256(pe.__data__).hexdigest() == prior['binarySha256']
    reg_ins = ns['decode'](base+0x643720)[0]
    registration = [rec(reg_ins[base+r]) for r in (0x646306, 0x64630d, 0x646312)]
    assert [r['bytes'] for r in registration] == ['488d1553850c00', 'b971020000', 'ff9308010000']
    managed_context = {'kind': 'exact-managed-peer-registration-context', 'entryPointerKind': None,
        'entryRegisters': {'rdx': 'mission'}, 'entryBiases': {'rdx': 0}, 'callbackId': 625,
        'nativeRegistration': registration, 'managedBinding': metadata['registration'],
        'proof': 'PeerExtensions passes Mission.Pointer as second explicit argument through the void(int32,uintptr) delegate; Windows x64 maps it to RDX with no hidden return buffer.'}
    caller, call, target = base+0x66a480, base+0x66a934, base+0x6535a0
    states, report = ns['analyze'](caller, ns['contracts'][caller])
    assert states is not None and report['status'] == 'converged'
    caller_ins = ns['cache'][caller][0]
    value = states[call].get('rdx')
    assert value and value[:2] == ('agent', 0)
    assert caller_ins[call].bytes.hex() == 'ff9090010000'
    assert caller_ins[call-9].bytes.hex() == '488b06'
    assert caller_ins[call-6].bytes.hex() == '498bd5'
    assert caller_ins[call-3].bytes.hex() == '488bce'
    slot = pe.get_data(0xb22998, 8)
    assert int.from_bytes(slot, 'little') == target and 0xb22998-0xb22808 == 0x190
    ctor_ins = ns['decode'](base+0x64ca70)[0]
