$ErrorActionPreference = 'Stop'
# Cecil reads metadata and CIL; game assemblies are never loaded for execution.
$bin = 'D:/SteamLibrary/steamapps/common/Mount & Blade II Bannerlord/bin/Win64_Shipping_Client'
Add-Type -Path "$bin/mono/lib/mono/gac/Mono.Cecil/0.11.0.0__0738eb9f132ed756/Mono.Cecil.dll"
function AllTypes($items) { foreach ($t in $items) { $t; AllTypes $t.NestedTypes } }
$assemblies = @(); $identities = @(); $types = @{}; $delegates = @(); $calls = @()
try {
    foreach ($name in @('TaleWorlds.MountAndBlade.AutoGenerated','TaleWorlds.MountAndBlade','TaleWorlds.Engine','TaleWorlds.Library','TaleWorlds.DotNet','TaleWorlds.Core')) {
        $path = Join-Path $bin "$name.dll"
        $a = [Mono.Cecil.AssemblyDefinition]::ReadAssembly($path)
        $assemblies += $a
        $hasher = [Security.Cryptography.SHA256]::Create()
        try { $digest = [BitConverter]::ToString($hasher.ComputeHash([IO.File]::ReadAllBytes($path))).Replace('-','').ToLowerInvariant() } finally { $hasher.Dispose() }
        $identities += [ordered]@{path=$path;sha256=$digest;mvid=$a.MainModule.Mvid.ToString()}
        foreach ($t in (AllTypes $a.MainModule.Types)) { $types[$t.FullName]=$t }
    }
    foreach ($owner in @('IMBAgent','IMBMission')) {
        $t = $types["ManagedCallbacks.ScriptingInterfaceOf$owner"]
        foreach ($n in $t.NestedTypes) {
            $m = $n.Methods | Where-Object Name -eq 'Invoke'
            if (!$m) { continue }
            $delegates += [ordered]@{type=$n.FullName;token=('0x{0:x8}' -f $m.MetadataToken.ToInt32());returnType=$m.ReturnType.FullName;parameters=@($m.Parameters | ForEach-Object {[ordered]@{name=$_.Name;type=$_.ParameterType.FullName}});attributes=@($n.CustomAttributes | ForEach-Object {$_.AttributeType.FullName})}
        }
    }
    $returns = @{}
    foreach ($d in $delegates) {
        if ($types.ContainsKey($d.returnType)) {
            $t = $types[$d.returnType]
            $returns[$d.returnType] = [ordered]@{isEnum=$t.IsEnum;attributes=$t.Attributes.ToString();size=$t.ClassSize;pack=$t.PackingSize;fields=@($t.Fields | Where-Object {!$_.IsStatic} | ForEach-Object {[ordered]@{name=$_.Name;type=$_.FieldType.FullName;offset=$_.Offset}})}
        }
    }
    foreach ($owner in @('TaleWorlds.MountAndBlade.Agent','TaleWorlds.MountAndBlade.Mission')) {
        foreach ($m in $types[$owner].Methods) {
            if (!$m.HasBody) { continue }
            foreach ($i in $m.Body.Instructions) {
                if ($i.OpCode.Name -eq 'callvirt' -and $i.Operand.ToString() -match 'IMB(Agent|Mission)::') {
                    $at=$m.Body.Instructions.IndexOf($i);$lo=[Math]::Max(0,$at-24)
                    $calls += [ordered]@{method=$m.FullName;instruction=$i.ToString();context=@($m.Body.Instructions[$lo..$at] | ForEach-Object {$_.ToString()})}
                }
            }
        }
    }
    [ordered]@{artifacts=$identities;delegates=$delegates;returnTypes=$returns;managedCallerContexts=$calls;gameExecuted=$false} | ConvertTo-Json -Depth 12
} finally { foreach ($a in $assemblies) { $a.Dispose() } }
